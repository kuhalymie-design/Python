# Q1. Python program to count positive and negative numbers in a list.

a = [10, -20, 30, -40, 50, -60, 0]
pos = 0      # to count +ve number here
neg = 0      # to count -ve number here
for n in a:
    if n > 0:
        pos += 1
    elif n < 0:
        neg += 1
print("Positive numbers:", pos)
print("Negative numbers:", neg)

