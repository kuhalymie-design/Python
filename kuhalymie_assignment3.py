# Q13. Data Cleaning Pipeline (map + filter + lambda)
# From a data pipeline:
#  a.)Remove negative numbers
#  b.) Square remaining numbers
#  c.) Keep only results > 50

# data = [-4, -1, 2, 4, 8]
# Output : [64]

data = [-4, -1, 2, 4, 8]

# using map + filter + lambda
cleaned = list(filter(lambda x: x > 50,map(lambda x: x**2, filter(lambda x: x >= 0, data))))
print(cleaned)

# Breakdown
# Step 1: remove negatives
positive_data = filter(lambda x: x >= 0, data) # Keeps only numbers 0 or greater → [2, 4, 8]
# Step 2: square numbers
squared_data = map(lambda x: x**2, positive_data) # Squares each number → [4, 16, 64]
# Step 3: keep numbers > 50 → [64]
final_data = list(filter(lambda x: x > 50, squared_data)) # list() → converts filter object to list so we can print
print(final_data)

# using for loop
result = []
for x in data:
    if x >= 0:            # Step a: remove negatives
        squared = x**2    # Step b: square
        if squared > 50:  # Step c: keep > 50
            result.append(squared)
print(result)

# Using list comprehension
result = [x**2 for x in data if x >= 0 and x**2 > 50]
print(result)